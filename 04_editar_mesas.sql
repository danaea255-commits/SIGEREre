USE saboros;

CREATE TABLE IF NOT EXISTS zonas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE
) ENGINE=InnoDB;

ALTER TABLE mesas
    ADD COLUMN pos_x INT NULL,
    ADD COLUMN pos_y INT NULL,
    ADD COLUMN activa TINYINT(1) NOT NULL DEFAULT 1;

INSERT IGNORE INTO zonas (nombre)
SELECT zona FROM mesas WHERE activa = 1 GROUP BY zona ORDER BY MIN(id);
